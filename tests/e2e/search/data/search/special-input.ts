export type SpecialInputOutcome =
  | { type: 'no-matches' }
  | { type: 'counter'; counter: string; productIds?: number[] }
  | { type: 'error-503' };

export interface SpecialInputRow {
  id: string;
  testId: string;
  description: string;
  query: string;
  httpStatus: number;
  outcome: SpecialInputOutcome;
  /** Expected value of the header search input after submit (null = not applicable, error page). */
  expectedInputValue: string | null;
  /** Query is a script/HTML/SQL injection payload. */
  security?: boolean;
  /** Row relies on the fuzzy matching of the site (observed behaviour, not a business rule). */
  fuzzy?: boolean;
}

